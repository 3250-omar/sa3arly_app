SELECT s.alias_text, t.id
FROM seed s
JOIN public.categories c ON c.name = s.category_name
JOIN public.item_templates t
  ON t.category_id = c.id
 AND t.name = s.item_name
 AND COALESCE(t.size, '') = s.item_size
ON CONFLICT DO NOTHING;
